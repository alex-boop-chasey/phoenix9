"""Keys: per-project HOME/keys/<project>.toml and the global secrets store HOME/secrets/<name>.env (owner-only)."""
import os
import re
import stat
import shutil
import tempfile
import tomllib
from contextlib import contextmanager
from pathlib import Path

from phoenix9 import atomic, events, paths, scrub, tomlw

NAME_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
HEADER = "generated by Phoenix; values live outside the repo"


class KeyError_(ValueError):
    """A key name or value Phoenix refuses (the message is plain words)."""


def _file(project: str) -> Path:
    """HOME/keys/<project>.toml."""
    if not project or "/" in project or project.startswith("."):
        raise KeyError_(f"'{project}' is not a project name.")
    return paths.keys() / f"{project}.toml"


def _load(project: str) -> list[dict]:
    """The stored rows ({name, value, secret}); [] when there is no file yet."""
    try:
        data = tomllib.loads(_file(project).read_text(encoding="utf-8"))
    except FileNotFoundError:
        return []
    return [{"name": r["name"], "value": r.get("value", ""), "secret": bool(r.get("secret", True))}
            for r in data.get("key", []) if isinstance(r.get("name"), str)]


def _save(project: str, rows: list[dict]) -> None:
    """Write the rows with the folder at 0700 and the file at 0600."""
    folder = paths.keys()
    folder.mkdir(parents=True, exist_ok=True)
    folder.chmod(0o700)
    text = _render(rows)
    atomic.write_text(_file(project), text, mode=0o600)


def _render(rows: list[dict]) -> str:
    """The keys file text (written by hand: only name, value, secret)."""
    out = []
    for r in rows:
        out.append("[[key]]\n"
                   f"name = {tomlw._string(r['name'])}\n"
                   f"value = {tomlw._string(r['value'])}\n"
                   f"secret = {'true' if r['secret'] else 'false'}\n")
    return "\n".join(out)


def _check_name(name: str) -> None:
    if not isinstance(name, str) or not NAME_RE.match(name):
        raise KeyError_(f"'{name}' is not a good key name: use letters, digits and underscores, "
                        "not starting with a digit.")


def list_keys(project: str) -> list[dict]:
    """Each key as {name, secret, has_value, value_if_not_secret}; secret values are never returned."""
    return [{"name": r["name"], "secret": r["secret"], "has_value": bool(r["value"]),
             "value_if_not_secret": None if r["secret"] else r["value"]} for r in _load(project)]


def _changed(project: str, what: str, name: str) -> None:
    """Rewrite .env.example and record project.changed (names only)."""
    write_env_example(project)
    events.emit("project.changed", project=project, what=what, key=name)


def _put(project: str, name: str, value: str, secret: bool) -> None:
    rows = [r for r in _load(project) if r["name"] != name]
    rows.append({"name": name, "value": value, "secret": secret})
    _save(project, rows)


def set_key(project: str, name: str, value: str, secret: bool = True) -> None:
    """Store a key value (replacing a key of the same name); an empty value is refused."""
    _check_name(name)
    if not value:
        raise KeyError_(f"The value for {name} is empty.")
    if "\n" in value or "\r" in value:
        raise KeyError_(f"The value for {name} has a line break, which an env file cannot hold.")
    _put(project, name, value, secret)
    _changed(project, "key set", name)


def set_secret_flag(project: str, name: str, secret: bool) -> bool:
    """Change whether a saved key is secret, keeping its value; False when there is no such key."""
    rows = _load(project)
    row = next((r for r in rows if r["name"] == name), None)
    if row is None:
        return False
    if row["secret"] != secret:
        row["secret"] = secret
        _save(project, rows)
        _changed(project, "key changed", name)
    return True


def get_value(project: str, name: str) -> str | None:
    """The saved value of a key (None when there is no such key); only the reveal endpoint may show it."""
    row = next((r for r in _load(project) if r["name"] == name), None)
    return None if row is None else row["value"]


def add_empty(project: str, name: str, secret: bool = True) -> bool:
    """Add a row waiting for a value; an existing key is left alone. Returns True when a row was added."""
    _check_name(name)
    if any(r["name"] == name for r in _load(project)):
        return False
    _put(project, name, "", secret)
    _changed(project, "key added", name)
    return True


def remove_key(project: str, name: str) -> bool:
    """Delete a key; returns False when there was no such key."""
    rows = _load(project)
    kept = [r for r in rows if r["name"] != name]
    if len(kept) == len(rows):
        return False
    _save(project, kept)
    _changed(project, "key removed", name)
    return True


def secret_values(project: str) -> list[str]:
    """The values of the secret keys (for scrubbing and the secret scan; never print them)."""
    return [r["value"] for r in _load(project) if r["secret"] and r["value"]]


def container_env(project: str) -> dict:
    """Every key that has a value, as NAME -> value (for a container's env file)."""
    return {r["name"]: r["value"] for r in _load(project) if r["value"]}


def write_env_example(project: str) -> None:
    """Write code/.env.example: non-secret NAME=value, secret NAME= (only when the project has a code folder)."""
    code = paths.projects() / project / "code"
    if not code.is_dir():
        return
    lines = [f"# {HEADER}"] + [f"{r['name']}=" if r["secret"] else f"{r['name']}={r['value']}"
                               for r in _load(project)]
    atomic.write_text(code / ".env.example", "\n".join(lines) + "\n")


@contextmanager
def env_file(project: str):
    """Yield a 0600 env file holding the project's keys (None when it has none); deleted afterwards."""
    values = container_env(project)
    if not values:
        yield None
        return
    folder = Path(tempfile.mkdtemp(prefix="phoenix-keys-"))
    try:
        path = folder / "project-keys.env"
        atomic.write_text(path, "".join(f"{k}={v}\n" for k, v in values.items()), mode=0o600)
        yield path
    finally:
        shutil.rmtree(folder, ignore_errors=True)


# ---------- global secrets store: HOME/secrets/<name>.env ----------
SECRET_FILE_RE = re.compile(r"^[a-z0-9-]+\.env$")


def secrets_dir() -> Path:
    """HOME/secrets, created or fixed to mode 0700."""
    folder = paths.secrets()
    folder.mkdir(parents=True, exist_ok=True)
    if stat.S_IMODE(folder.stat().st_mode) != 0o700:
        folder.chmod(0o700)
    return folder


def _secret_path(file_name: str) -> Path:
    """The path of a secrets file, refusing names that are not like 'service-supabase.env'."""
    if not isinstance(file_name, str) or not SECRET_FILE_RE.match(file_name):
        raise KeyError_(f"'{file_name}' is not a secrets file name: use lowercase letters, digits and dashes, "
                        "ending in .env.")
    return secrets_dir() / file_name


def write_secret_file(file_name: str, values: dict[str, str]) -> None:
    """Write NAME=value lines to a 0600 secrets file (replacing it); refuses a symlink or a line break."""
    target = _secret_path(file_name)
    if target.is_symlink():
        raise KeyError_(f"{file_name} is a symlink; Phoenix will not write through it.")
    lines = []
    for name, value in values.items():
        _check_name(name)
        if not isinstance(value, str) or not value:
            raise KeyError_(f"The value for {name} is empty.")
        if "\n" in value or "\r" in value:
            raise KeyError_(f"The value for {name} has a line break, which an env file cannot hold.")
        lines.append(f"{name}={value}\n")
    fd, tmp = tempfile.mkstemp(dir=target.parent, prefix=f".{file_name}.")
    os.close(fd)
    os.unlink(tmp)
    try:
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write("".join(lines))
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, target)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise
    scrub.add_secrets(values.values())


def _check_secret_file(file_name: str) -> Path:
    """The path of an existing secrets file that is not a symlink and is owner-only."""
    path = _secret_path(file_name)
    if path.is_symlink():
        raise KeyError_(f"{file_name} is a symlink; Phoenix will not read it.")
    if not path.is_file():
        raise KeyError_(f"There is no secrets file called {file_name}.")
    mode = stat.S_IMODE(path.stat().st_mode)
    if mode & 0o077:
        raise KeyError_(f"{file_name} can be read by other users (mode {mode:o}); run chmod 600 on it.")
    return path


def read_secret_file(file_name: str) -> dict[str, str]:
    """The NAME=value pairs in a secrets file; every value joins the scrub list."""
    values = scrub.read_env_file(_check_secret_file(file_name))
    scrub.add_secrets(values.values())
    return values


def remove_secret_file(file_name: str) -> bool:
    """Delete a secrets file; False when there was none."""
    path = _secret_path(file_name)
    if not path.is_symlink() and not path.exists():
        return False
    path.unlink()
    return True


def secret_files() -> list[dict]:
    """Each secrets file as {file, names, modified}: names only, never values."""
    folder = paths.secrets()
    if not folder.is_dir():
        return []
    out = []
    for path in sorted(folder.glob("*.env")):
        if path.is_symlink() or not path.is_file() or not SECRET_FILE_RE.match(path.name):
            continue
        try:
            names = sorted(scrub.read_env_file(path)) if not stat.S_IMODE(path.stat().st_mode) & 0o077 else []
        except OSError:
            names = []
        out.append({"file": path.name, "names": names, "modified": path.stat().st_mtime})
    return out
