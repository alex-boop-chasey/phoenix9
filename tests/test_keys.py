import pytest

from helpers.stepunit import load, make_ctx, make_work
from phoenix9 import keys, paths, runs, scrub
from phoenix9.runner import Runner

SECRET = "sk-test-VERY-secret-value-12345"
DATA = Path(__file__).parent / "data" / "runlib"


def mode(path):
    return stat.S_IMODE(os.stat(path).st_mode)


def test_keys_file_modes_0600_dir_0700():
    keys.set_key("demo", "API_KEY", SECRET, True)
    assert mode(paths.keys()) == 0o700
    assert mode(paths.keys() / "demo.toml") == 0o600


def test_set_validates_name_and_empty_value():
    for bad in ("1ABC", "has space", "A-B", ""):
        with pytest.raises(keys.KeyError_):
            keys.set_key("demo", bad, "value", True)
    with pytest.raises(keys.KeyError_):
        keys.set_key("demo", "OK_NAME", "", True)
    keys.set_key("demo", "OK_NAME", "one", False)
    keys.set_key("demo", "OK_NAME", "two", False)      # replaces
    assert keys.container_env("demo") == {"OK_NAME": "two"}


def test_list_never_returns_secret_values():
    keys.set_key("demo", "API_KEY", SECRET, True)
    keys.set_key("demo", "PUBLIC_URL", "https://x.test", False)
    keys.add_empty("demo", "LATER", True)
    rows = {r["name"]: r for r in keys.list_keys("demo")}
    assert SECRET not in json.dumps(rows)
    assert rows["API_KEY"] == {"name": "API_KEY", "secret": True, "has_value": True, "value_if_not_secret": None}
    assert rows["PUBLIC_URL"]["value_if_not_secret"] == "https://x.test"
    assert rows["LATER"]["has_value"] is False
    assert keys.secret_values("demo") == [SECRET]
    assert "LATER" not in keys.container_env("demo")


def test_env_example_contents(phoenix_env):
    (phoenix_env["projects"] / "demo" / "code").mkdir(parents=True)
    keys.set_key("demo", "API_KEY", SECRET, True)
    keys.set_key("demo", "PUBLIC_URL", "https://x.test", False)
    text = (phoenix_env["projects"] / "demo" / "code" / ".env.example").read_text()
    assert "generated by Phoenix; values live outside the repo" in text.splitlines()[0]
    assert "API_KEY=\n" in text and "PUBLIC_URL=https://x.test\n" in text
    assert SECRET not in text
    keys.remove_key("demo", "PUBLIC_URL")
    assert "PUBLIC_URL" not in (phoenix_env["projects"] / "demo" / "code" / ".env.example").read_text()


def test_container_env_passed_as_env_file_not_argv(tmp_path, adapters):
    mod = load("acceptance")
    keys.set_key("proj", "API_KEY", SECRET, True)
    work = make_work(tmp_path)
    ctx = make_ctx(tmp_path, adapters, work, "acceptance")
    ctx.task["done_when"] = [{"text": "`echo hi`", "command": "echo hi"}]
    seen = {}
    real_run = adapters.docker.run

    def spy(argv, *a, **k):
        path = Path(argv[argv.index("--env-file") + 1])
        seen["path"], seen["text"], seen["mode"] = path, path.read_text(), mode(path)
        seen["argv"] = list(argv)
        return real_run(argv, *a, **k)
    adapters.docker.run = spy
    assert mod.run(ctx).status == "pass"
    assert f"API_KEY={SECRET}" in seen["text"] and seen["mode"] == 0o600
    assert SECRET not in " ".join(seen["argv"]) and not any(a.startswith("API_KEY") for a in seen["argv"])
    assert not seen["path"].exists()


def test_secret_values_scrubbed_in_run_log(tmp_path, phoenix_env, adapters):
    code = paths.projects() / "proj" / "code"
    code.mkdir(parents=True)
    import subprocess
    for args in (["init", "-q", "-b", "main"], ["add", "-A"]):
        subprocess.run(["git", "-C", str(code), *args], check=True, capture_output=True)
    (code / "README.md").write_text("hi\n")
    subprocess.run(["git", "-C", str(code), "add", "-A"], check=True)
    subprocess.run(["git", "-C", str(code), "-c", "user.email=t@t", "-c", "user.name=t", "commit", "-q", "-m", "1"],
                   check=True, capture_output=True)
    lib = tmp_path / "lib"
    shutil.copytree(DATA, lib)
    (lib / "steps" / "builder" / "run.py").write_text(
        "from phoenix9 import keys\nfrom phoenix9.stepctx import StepResult\n\n\n"
        "def run(ctx):\n    ctx.log('value is ' + keys.secret_values(ctx.project.name)[0])\n"
        "    return StepResult('pass')\n")
    keys.set_key("proj", "API_KEY", SECRET, True)
    spec = tmp_path / "spec.md"
    spec.write_text("# Spec: T\n\n## Task 1: First\nGoal: g.\nDone when:\n- it works fine\n")
    run_dir = runs.create_run("proj", spec, {"max_tries": 1, "on_failure": "continue"})
    Runner(adapters, lib).drive(run_dir)
    log = (run_dir / "logs" / "builder.log").read_text()
    assert "[secret]" in log and SECRET not in log
    # nothing under HOME or the project folder holds the value, except HOME/keys/
    for root in (phoenix_env["home"], paths.projects()):
        for f in root.rglob("*"):
            if f.is_file() and paths.keys() not in f.parents and ".git" not in f.parts:
                assert SECRET.encode() not in f.read_bytes(), f
